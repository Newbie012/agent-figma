#!/usr/bin/env node
// Writes docs/reference/commands.md from the command catalog, which ADR-005 makes
// the source of truth for help, discovery and completion. Run with --check in CI
// so a command that gains a flag cannot ship with documentation that predates it.
import { readFile, writeFile } from "node:fs/promises"
import { fileURLToPath } from "node:url"

const target = fileURLToPath(new URL("../docs/reference/commands.md", import.meta.url))
const { commandGroups, commandMetadata, flagCatalog, isRequired, signatureOf, universalFlags, usageOf } =
  await import("../src/cli/metadata.ts")

const escape = (value) => value.replaceAll("|", "\\|")

const flagRows = (flags, command) =>
  flags.map((flag) => {
    const info = flagCatalog[flag] ?? { summary: "" }
    const name = info.value === undefined ? flag : `${flag} ${info.value}`
    const required = command !== undefined && isRequired(command, flag) ? " (required)" : ""
    return `| \`${escape(name)}\` | ${escape(info.summary)}${required} |`
  })

const commandSection = (command) => [
  `### \`${signatureOf(command)}\``,
  "",
  command.summary,
  "",
  ...(command.endpoints === undefined ? [] : [`Reads \`${command.endpoints.join("`, `")}\`.`, ""]),
  ...(command.scopes === undefined ? [] : [`Scopes: \`${command.scopes.join("`, `")}\`.`, ""]),
  ...(command.safety === "read" ? [] : ["Deletes local state. It never changes anything in Figma.", ""]),
  "```bash",
  usageOf(command),
  "```",
  "",
  ...(command.flags === undefined || command.flags.length === 0
    ? []
    : ["| Flag | Meaning |", "| --- | --- |", ...flagRows(command.flags, command), ""]),
  ...command.examples.flatMap((example) => ["```bash", example, "```", ""]),
  `Answers ${command.output}.`,
  ""
]

const document = [
  "# Commands",
  "",
  "Every command `agent-figma` exposes, with the flags it takes and what it answers.",
  "",
  "<!-- Generated by scripts/write-command-reference.mjs from the command catalog. Run `pnpm docs:write` after changing it. -->",
  "",
  "The catalog is the source of truth, and the CLI reads it back to you:",
  "",
  "```bash",
  "agent-figma describe --json",
  "agent-figma COMMAND --help",
  "agent-figma COMMAND --help --json",
  "```",
  "",
  "## Flags every command takes",
  "",
  "| Flag | Meaning |",
  "| --- | --- |",
  ...flagRows(universalFlags),
  "",
  ...commandGroups.flatMap((group) => [
    `## ${group}`,
    "",
    ...commandMetadata.filter((command) => command.group === group).flatMap(commandSection)
  ])
].join("\n").replace(/\n{3,}/g, "\n\n")

const current = await readFile(target, "utf8").catch(() => "")

if (process.argv.includes("--check")) {
  if (current === document) {
    console.log("docs/reference/commands.md matches the command catalog.")
    process.exit(0)
  }
  console.error("docs/reference/commands.md is behind the command catalog. Run `pnpm docs:write`.")
  process.exit(1)
}

await writeFile(target, document)
console.log(`Wrote ${target}`)
